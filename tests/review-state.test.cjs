const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const file = require('node:path').join(__dirname, '../assets/js/review-state.js');
assert.ok(fs.existsSync(file), 'Project review state must exist');
const context = { structuredClone };
vm.runInNewContext(fs.readFileSync(file, 'utf8'), context);
const M = context.MROReviewState;
const defs = [0,1,2].map(i => ({columns:['Name','Value'], rows:[['Item '+i,'10']]}));
const db = { checks:{old:'preserved'} };
const a = M.load(db, 'A', defs);
assert.equal(M.canOpen(a,1),false);
assert.equal(M.finish(a,1),false,'Cannot complete a locked step');
M.applyImport(a,0,[['Imported','20']],'sample.xlsx','append');
assert.equal(M.canOpen(a,1),false,'Import must not unlock the next step');
assert.equal(a.rows[0].length,2);
assert.equal(M.load(db,'A',defs),a,'Load must retain the same project records');
assert.equal(M.finish(a,0),true);
assert.equal(M.canOpen(a,1),true);
assert.equal(M.applyImport(a,0,[['Wrong','0']],'bad.xlsx','replace'),false,'Completed steps are read only');
M.finish(a,1);
const snapshot=JSON.stringify(a.rows);
M.reopen(a,0);
assert.equal(JSON.stringify(a.done),'[false,false,false]');
assert.equal(JSON.stringify(a.rows),snapshot,'Reopen must preserve all imported data');
assert.equal(M.canOpen(a,1),false);
const b=M.load(db,'B',defs);
assert.equal(b.rows[0].length,1,'Projects must not share imported data');
assert.equal(db.checks.old,'preserved','Do not overwrite legacy data');
db.projectReviews.C={done:[false,true,true],rows:a.rows,source:a.source};
assert.equal(JSON.stringify(M.load(db,'C',defs).done),'[false,false,false]','Repair noncontiguous saved completion');
const restored=JSON.parse(JSON.stringify(db));
assert.equal(M.load(restored,'A',defs).rows[0][1][0],'Imported','Reload retains data');
assert.equal(M.canOpen(a,NaN),false);
assert.equal(M.canOpen(a,-1),false);
assert.equal(M.canOpen(a,3),false);
console.log('PASS: sequential access, import, reopen, isolation, persistence, migration');
