"""Package the separate, interactive inspection UX wireframe for offline review."""
from pathlib import Path
import zipfile

root = Path(__file__).resolve().parents[1]
source = root / 'wireframe'
# Reuse the prototype's small offline XLSX exporter without its UI or state.
inspection = (root / 'assets/js/inspection.js').read_text(encoding='utf-8')
exporter = inspection[inspection.index('function inspectionWorkbook('):inspection.index('function exportInspectionTable(')]
(source / 'workbook.js').write_text('// Shared offline XLSX exporter, generated by build-wireframe.py.\n' + exporter, encoding='utf-8')
html = (source / 'index.html').read_text(encoding='utf-8')
html = html.replace('<link rel="stylesheet" href="style.css">', '<style>\n' + (source / 'style.css').read_text(encoding='utf-8') + '\n</style>')
for name in ['workbook.js', 'app.js']:
    html = html.replace(f'<script src="{name}"></script>', '<script>\n' + (source / name).read_text(encoding='utf-8') + '\n</script>')
# Navigation outside this focused wireframe is online/source-only; keep the
# portable version self-contained and explain the destination when clicked.
import re
html = re.sub(r'href="\.\./index\.html#[^"]+"', 'href="#" onclick="message(\'Bagian ini tersedia di mockup MRO utama. Wireframe berfokus pada Detail Project.\');return false"', html)
out = root / 'deliverables'
out.mkdir(exist_ok=True)
target = out / 'WIREFRAME-DETAIL-PROJECT.html'
target.write_text(html, encoding='utf-8')
with zipfile.ZipFile(out / 'MRO-Wireframe-Detail-Project.zip', 'w', zipfile.ZIP_DEFLATED) as archive:
    archive.write(target, target.name)
    archive.write(source / 'README.txt', 'PANDUAN-WIREFRAME.txt')
with zipfile.ZipFile(out / 'MRO-Wireframe-Detail-Project.zip') as archive:
    assert archive.testzip() is None
assert '<script src=' not in html and '<link rel="stylesheet"' not in html
print('Packaged standalone wireframe and ZIP:', target.stat().st_size, 'bytes')
